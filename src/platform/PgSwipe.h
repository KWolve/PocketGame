/*
 * PgSwipe.h - 全局「右滑返回」手势检测（2026-09-16 用户需求）
 *
 * 用户原话：「应用界面内模仿 android 手机右滑有个动效图片后返回主页」。
 *
 * 为什么抽成独立模块：本工程有**两处**要判同一个手势，而且它们都拿得到触摸事件：
 *   ① 全局导航栏（navibar.cc）—— 它的触摸回调是**全局监听**，
 *      任何页面/浮层都会收到（不受窗口命中影响，见 statusbar.cc 的实测记录）
 *      ⇒ 独立 ftu 页的"右滑返回"在这里统一处理，**不用改 16 个页面**；
 *   ② 主界面（mainLogic.cc）—— 画布游戏是"主界面内的整屏 window"，
 *      不是独立 Activity，`EASYUICONTEXT->goBack()` 对它无效，
 *      必须在主界面自己判（右滑 = 退出游戏回列表）。
 *
 * 指纹（为什么这么定 —— 2026-09-16 真机校准过两轮）：
 *   · ★★ **必须从屏幕左侧 48px 内起手**（仿 Android 的边缘返回手势）。
 *     第一版只判「水平位移 ≥90px」，结果**推箱子里一次 140px 的拖拽直接把游戏退了**
 *     （真机实测日志：`右滑返回 -> 退出当前游戏回列表`）—— 画布游戏里有大量横向拖拽
 *     （推箱子滑格、消消乐交换、俄罗斯方块横移），只靠距离阈值分不开。
 *     加上「边缘起手」之后，游戏内的正常操作起点几乎不会落在最左 48px 内。
 *   · **水平位移 ≥ 120px**（屏宽 480 的 25%）—— 与上一条一起构成双保险；
 *   · **水平占优**：纵向偏移 ≤ 70px —— 竖直滑动是列表滚动；
 *   · **时长 ≤ 900ms** —— 慢悠悠地从左拖到右不算手势。
 * 判定在 **抬手** 那一刻做（跟手阶段只更新进度，用于画动效）。
 */
#ifndef PG_SWIPE_H_
#define PG_SWIPE_H_

namespace pg {

/** 手指按下：开始记录本次手势。 */
void swipeDown(int x, int y);
/** 手指移动：更新跟手进度（不改判定）。 */
void swipeMove(int x, int y);
/** 手指抬起：返回 true = 这一下判定为「右滑返回」。判定后状态复位。 */
bool swipeUp(int x, int y);
/** 取消（触摸 cancel / 页面切走）：直接复位，不判定。 */
void swipeCancel();

/** 跟手进度 0..255（0 = 还没滑出阈值或**手势已结束**，255 = 已达标）。
 *  ⚠️ 抬手/取消之后一定归 0（在 swipeUp/swipeCancel 里复位）——
 *     所以"按 pr > 0 显示浮层"的写法不会粘住。曾经的 bug 正是抬手不复位，
 *     导致浮层永久挂着（见 PgSwipe.cpp 的说明）。 */
int swipeProgress();

/** 上一笔手势是否被判成右滑（UP 之后仍然有效，供"播放完动画再收尾"用）。 */
bool swipeTriggered();

/** 清掉「上一笔判成右滑」的标记（动画播完后调用）。 */
void swipeClearTriggered();

/* ==================== 是谁在处理这次右滑？ ====================
 * ★ 为什么需要这个标志（2026-09-16 实测踩到）：
 *   全局导航栏（navibar）与主界面（mainLogic）**都会**收到同一次触摸
 *   （navibar 的全局监听不受窗口命中影响），于是**两个人都判同一笔手势**。
 *   游戏里就出问题了：navibar 先判成右滑 → 调 `EASYUICONTEXT->goBack()`，
 *   可画布游戏是"主界面内的整屏 window"、不是 Activity ⇒ goBack() 什么也不做；
 *   等 mainLogic 收到抬手指时，状态已被判过（swipeUp 返回 false）⇒ 游戏退不出去。
 *
 * 解法：主界面每帧同步"是否在游戏里"，
 *   · 游戏里 → 由 **mainLogic** 负责退游戏（navibar 不 goBack）；
 *   · 不在游戏（独立 ftu 页/菜单）→ 由 **navibar** 负责 goBack。
 * 两边的 UP 分支都改成读 `swipeTriggered()`（"这一笔是不是被判成右滑"），
 * 而不是本次 `swipeUp()` 的返回值 —— 这样谁先收到抬指都不影响结论。 */
void setGameMode(bool on);
bool gameMode();

}  // namespace pg

#endif  // PG_SWIPE_H_
