/*
 * PgNavi.h - 全局导航栏（navibar）的外部状态接口
 *
 * ============================ 为什么需要它 ============================
 * 导航栏是 **topmost + 常显** 的 480x52 窗口（位置 (0,0)），也就是说
 * **屏幕顶部 y ∈ [0,52) 这一条永远是它**。2026-09-16 的用户需求是
 * 「把 Ui 目录下的 json 布局全部检讨一遍，有 UI 区域被盖就告警并修复」——
 * 检讨下来只有两类是"页面自己怎么改都救不了"的，本文件就是给它们的接口：
 *
 * ---- ① 页面专属名字（setNaviTitle）----
 *   navibar 原来只按 `EASYUICONTEXT->currentAppName()` 查一张**静态表**显示标题
 *   （见 navibar.cc 的 kTitleMap），所以它只会显示 Activity 级的名字
 *   （"口袋游戏机" / "时钟套件"）。但有两处的名字是**页面级**的：
 *     · 画布游戏里，页面顶部的 TextGameTitle 显示的是**当前游戏名**；
 *     · 时钟套件切到 WinWorld 子页时，TextWorldTitle 显示的是"世界时钟"。
 *   这两块现在都**整块被 navibar 盖死**（它们都在 y<52），而页面里再没有第二个位置
 *   放它们（游戏 HUD 下面就是 540 高的画布；WinWorld 的 10 行城市已铺到 y=700）。
 *   ⇒ 正解不是挪页面，而是**让状态栏直接显示这个名字**：调用方在进入时
 *     `pg::setNaviTitle("三消")`、退出时 `pg::setNaviTitle(0)` 恢复自动映射。
 *
 * ---- ② 视频播放页（setVideoPage）----
 *   IPTV / 局域网摄像头 / 投屏三个播放页的视频区是 **480x700 @y=0**，而且逻辑层是按
 *   "等比铺满"下发 `set_pos` 的 ⇒ navibar 会永久压住画面最上面 52px（= 画面的 7.4%，
 *   是**真丢内容**，不是黑边）。视频层坐标不能动（硬件 disp 层，改坐标风险高），
 *   所以这里走"屏保"那条老路：**播放页里把导航栏收起来**，退出即恢复。
 *
 * ============================ ⚠️ 谁负责清标志 ============================
 * 两个标志都是**全局粘性**的（与 PgSwipe.h 的 setGameMode 同一类），
 * 所以在下列时机必须复位，否则会粘到别的页面上：
 *   · 视频页：回到列表页时 clear（iptv/camera 各一个函数、投屏是 stopCast()），
 *     另外 navibar.cc 里还有一道**自愈兜底**（发现当前 Activity 不是那三个播放页
 *     就自动清掉），覆盖 Activity 被异常关掉的路径；
 *   · 标题覆盖：页面**离开时**必须 `setNaviTitle(0)`（navibar 不替它清 ——
 *     它无法区分"页面故意设的名字"与"页面走掉了没清"）。
 *
 * ⚠️ 实现放在 `PgNavi.cpp`（platform/ 下的 .cpp 会被 fun 自动纳入构建，
 *    与另外 24 个 platform 源文件同一待遇）。
 */
#ifndef PG_NAVI_H_
#define PG_NAVI_H_

namespace pg {

/* ==================== ① 导航栏标题覆盖 ==================== */

/** 临时覆盖导航栏标题（传 0 或 "" = 恢复按 Activity 名自动映射）。
 *  调用方负责在**退出该页面/子页时**传 0 复原。内容不变时不重写（幂等）。 */
void setNaviTitle(const char *title);

/** 当前覆盖值；返回 0 = 没有覆盖（走自动映射）。 */
const char *naviTitleOverride();

/* ==================== ② 视频播放页 ==================== */

/** 标记"现在在视频播放页"（进播放页 true，回列表页 false）。
 *  navibar 会据此把自己的窗口收起来，把视频画面整块让出来。 */
void setVideoPage(bool on);

/** 是否处于视频播放页（由 navibar 每拍读取）。 */
bool videoPage();

}  // namespace pg

#endif  // PG_NAVI_H_
